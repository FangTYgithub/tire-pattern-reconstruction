# Rasterize alternating narrow and wide lines with the same line-family geometry.

import copy
import math
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / 'src'))
sys.path.insert(0, str(HERE))

W_NARROW_MM = 0.75
W_WIDE_MM = 1.25
W_REF_MM = 1.0
PARITY_WIDE = 1


def class_of_id(k) -> np.ndarray:
    return (np.asarray(k, np.int64) % 2 == PARITY_WIDE).astype(np.int64)


def coded_pattern(s_mm: float, phi_deg: float, phase_frac: float, w_narrow_mm: float = W_NARROW_MM, w_wide_mm: float = W_WIDE_MM):
    import m2_pattern as M2
    pn, mn = M2.generate_pattern('olines', spacing_mm=float(s_mm), feature_size_mm=float(w_narrow_mm), line_angle_deg=float(phi_deg), line_phase_frac=float(phase_frac))
    pw, mw = M2.generate_pattern('olines', spacing_mm=float(s_mm), feature_size_mm=float(w_wide_mm), line_angle_deg=float(phi_deg), line_phase_frac=float(phase_frac))
    pr, mr = M2.generate_pattern('olines', spacing_mm=float(s_mm), feature_size_mm=float(W_REF_MM), line_angle_deg=float(phi_deg), line_phase_frac=float(phase_frac))
    on, ow, orf = mn['olines'], mw['olines'], mr['olines']
    assert np.array_equal(np.asarray(on['ids']), np.asarray(ow['ids'])) and tuple(on['centre_uv']) == tuple(ow['centre_uv']) and abs(on['spacing_px'] - ow['spacing_px']) < 1e-12, 'narrow / wide families differ'
    pn = np.asarray(pn, np.float32); pw = np.asarray(pw, np.float32); H, W = pn.shape
    cu, cv = on['centre_uv']; phi = math.radians(float(phi_deg)); nx, ny = math.cos(phi), math.sin(phi)
    vv, uu = np.mgrid[0:H, 0:W]; q = (uu - cu) * nx + (vv - cv) * ny; r = q / on['spacing_px'] - float(phase_frac); k = np.round(r).astype(np.int64)
    wide = class_of_id(k) == 1
    pat = np.where(wide, pw, pn).astype(np.float32)
    ids = np.asarray(on['ids'], np.int64); cls = class_of_id(ids)
    lit_by_class = {int(c): int(pat[(class_of_id(k) == c)].sum()) for c in (0, 1)}
    meta = copy.deepcopy(mn)
    meta['olines'] = dict(copy.deepcopy(orf), code=dict(period=2, parity_wide=PARITY_WIDE, widths_mm=dict(narrow=float(w_narrow_mm), wide=float(w_wide_mm)), widths_px=dict(narrow=float(on['width_px']), wide=float(ow['width_px'])), nominal_width_px=float(orf['width_px']),
                                                           class_of_id='(k % 2 == parity_wide) -> wide (1) else narrow (0); k = design line id', n_lines_by_class={int(c): int((cls == c).sum()) for c in (0, 1)}, lit_px_by_class=lit_by_class, lit_px_total=int(pat.sum()),
                                                           rule='pixel takes the raster of its nearest line class; narrow / wide rasters generated by m2_pattern olines with identical centres'))
    meta['olines']['lit_px_total'] = int(pat.sum()); meta['pattern_kind'] = 'coded_width_p2'
    return pat, meta, dict(narrow=pn, wide=pw, ref=np.asarray(pr, np.float32), ref_meta=mr)


def uncoded_pattern(s_mm: float, phi_deg: float, phase_frac: float, w_mm: float = W_REF_MM):
    import m2_pattern as M2
    p, m = M2.generate_pattern('olines', spacing_mm=float(s_mm), feature_size_mm=float(w_mm), line_angle_deg=float(phi_deg), line_phase_frac=float(phase_frac))
    m = copy.deepcopy(m); m['pattern_kind'] = 'uncoded'
    return np.asarray(p, np.float32), m


def pattern_for_spec(spec: dict):

    if spec.get('pattern_kind') == 'coded_width_p2':
        pat, meta, _ = coded_pattern(spec['s_mm'], spec['phi_deg'], spec['phase_frac']); return pat, meta
    return uncoded_pattern(spec['s_mm'], spec['phi_deg'], spec['phase_frac'], float(spec.get('w_mm', W_REF_MM)))
